import {test,expect} from "@playwright/test";
test("authoring replay through actual admin and learner pages",async({page,browser})=>{
  await page.route("http://localhost:8000/api/v1/**",route=>route.continue({url:route.request().url().replace("http://localhost:8000","http://host.docker.internal:8104")}));
  await page.goto("http://host.docker.internal:3000/login");
  await page.getByLabel("Email",{exact:true}).fill("authoring-admin@example.com");
  await page.getByLabel("Mật khẩu",{exact:true}).fill("BrowserFixtureOnly123!");
  await page.getByRole("button",{name:"Đăng nhập",exact:true}).click();
  await expect(page).toHaveURL(/learn/);
  await page.goto("http://host.docker.internal:3000/admin/questions");
  await page.getByLabel("Nội dung câu hỏi",{exact:true}).fill("Browser authoring replay "+Date.now());
  await page.getByLabel("Chủ đề cần tìm").fill("Synthetic topic");
  await page.getByRole("button",{name:"Tìm tài liệu liên quan",exact:true}).click();
  await expect(page.getByText("Synthetic browser source",{exact:false}).first()).toBeVisible();
  await page.getByRole("button",{name:"Đề xuất đáp án và tiêu chí",exact:true}).click();
  await expect(page.getByLabel("Đáp án tham khảo (admin sửa và duyệt)")).toHaveValue(/Replay/);
  await page.getByLabel("Đáp án tham khảo (admin sửa và duyệt)").fill("Admin edited replay answer");
  const saved=page.waitForResponse(r=>r.url().endsWith("/admin/questions")&&r.request().method()==="POST");
  await page.getByRole("button",{name:"Lưu câu hỏi và rubric",exact:true}).click();
  const question=await(await saved).json();
  expect(question.is_available).toBe(false);
  await page.screenshot({path:"/workspace/data/authoring/checks-20261112/admin-desktop.png",fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:"/workspace/data/authoring/checks-20261112/admin-mobile.png",fullPage:true});
  await page.getByRole("button",{name:"Đưa vào sử dụng",exact:true}).click();
  await expect(page.getByRole("button",{name:"Ngừng sử dụng",exact:true})).toBeVisible();
  const context=await browser.newContext();
  const learner=await context.newPage();
  await learner.route("http://localhost:8000/api/v1/**",route=>route.continue({url:route.request().url().replace("http://localhost:8000","http://host.docker.internal:8104")}));
  await learner.goto("http://host.docker.internal:3000/login");
  await learner.getByLabel("Email",{exact:true}).fill("authoring-learner@example.com");
  await learner.getByLabel("Mật khẩu",{exact:true}).fill("BrowserFixtureOnly123!");
  await learner.getByRole("button",{name:"Đăng nhập",exact:true}).click();
  await expect(learner).toHaveURL(/learn/);
  await learner.getByRole("combobox").selectOption(question.question_id);
  await learner.getByLabel("Câu trả lời",{exact:true}).fill("Synthetic learner answer");
  const submitted=learner.waitForResponse(r=>r.url().endsWith("/practice/attempts")&&r.request().method()==="POST");
  await learner.getByRole("button",{name:"Gửi câu trả lời",exact:true}).click();
  const attempt=await(await submitted).json();
  expect(attempt.retrieval.effective_strategy).toBe("approved_package");
  expect(attempt.retrieval.neo4j_queries).toBe(0);
  expect(attempt.retrieval.vector_search).toBe(false);
  await expect(learner.getByTestId("practice-result")).toBeVisible();
  await learner.reload();
  await expect(learner.getByTestId("practice-result")).toBeVisible();
  await context.close();
});
