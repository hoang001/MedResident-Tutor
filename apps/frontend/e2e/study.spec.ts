test("self-study persists drafts and submits without grades", async ({page}) => {
  await login(page);
  await page.getByRole("link", {name: "Tự luyện", exact: true}).click();
  await page.getByLabel("Nguồn câu hỏi", {exact: true}).selectOption("book");
  await expect(page.getByText("Câu hỏi thử giao diện: bạn đã đọc trích dẫn chưa?", {exact: true})).toBeVisible();
  await page.getByRole("button", {name: "Chọn 5 câu đầu trang"}).click();
  await page.getByRole("button", {name: "Bắt đầu bài 1 câu"}).click();
  await expect(page).toHaveURL(/session=/);
  await page.getByLabel("Câu trả lời 1", {exact: true}).fill("Tôi đã kiểm tra nguồn trước khi tự trả lời.");
  await page.getByRole("button", {name: "Lưu nháp", exact: true}).click();
  await expect(page.getByText("Đã lưu bản nháp vào tài khoản.", {exact: true})).toBeVisible();
  await page.reload();
  await expect(page.getByLabel("Câu trả lời 1", {exact: true})).toHaveValue("Tôi đã kiểm tra nguồn trước khi tự trả lời.");
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", {name: "Hoàn tất bài", exact: true}).click();
  await expect(page.getByText("Đã hoàn tất và lưu bài. Bài chưa được chấm điểm.", {exact: true})).toBeVisible();
  await expect(page.getByLabel("Câu trả lời 1", {exact: true})).toBeDisabled();
  const id = new URL(page.url()).searchParams.get("session");
  const response = await api(page, `/study/sessions/${id}`);
  const session = await response.json();
  expect(session.status).toBe("submitted"); expect(session.score).toBeNull(); expect(session.graded).toBe(false);
  await page.getByRole("link", {name: "Tiến độ", exact: true}).click();
  await expect(page.getByText(/Đã hoàn tất · chưa chấm điểm/).first()).toBeVisible();
});

test("source PDF keeps authentication outside URLs and fits a phone screen", async ({page}) => {
  await login(page);
  await page.setViewportSize({width: 390, height: 844});
  await page.goto("/sources?id=SRC_ORTHO_TEXTBOOK_001&page=8");
  await expect(page.getByRole("heading", {name: "Sách dùng trong kiểm thử", exact: true}).last()).toBeVisible();
  const pdfResponse = page.waitForResponse(r => r.url().includes("/knowledge/pdf/"));
  await page.getByRole("button", {name: "Mở PDF gốc · trang 8"}).click();
  const response = await pdfResponse;
  expect(response.status()).toBe(200);
  expect(response.url()).not.toMatch(/token|key|Authorization/);
  expect(response.headers()["content-type"]).toContain("application/pdf");
  await expect(page.getByTitle("Sách dùng trong kiểm thử, trang 8")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});

test("admin records source review while learner can only read its history", async ({page}) => {
  const reviewNote = `Đã đối chiếu trích dẫn của dữ liệu kiểm thử. ${randomUUID()}`;
  await login(page, "fixture-admin@example.com");
  await page.goto("/knowledge?id=FIXTURE%3ACONDITION");
  await page.getByText(/Lịch sử đối chiếu nguồn \(/).click();
  await page.getByLabel("Kết quả đối chiếu").selectOption("source_checked");
  await page.getByLabel("Nhận xét đối chiếu").fill(reviewNote);
  await page.getByRole("button", {name: "Ghi kết quả đối chiếu"}).click();
  await expect(page.getByText("Đã ghi nhận kết quả đối chiếu nguồn.", {exact: true})).toBeVisible();
  await page.getByRole("button", {name: "Đăng xuất", exact: true}).click();
  await page.goto("/login");
  // The history is readable by learners, but the review form is admin-only.
  await page.getByLabel("Email", {exact: true}).fill("second@example.com");
  await page.getByLabel("Mật khẩu", {exact: true}).fill("BrowserFixtureOnly123!");
  await page.getByRole("button", {name: "Đăng nhập", exact: true}).click();
  await expect(page).toHaveURL(/\/learn/);
  await page.goto("/knowledge?id=FIXTURE%3ACONDITION");
  await page.getByText(/Lịch sử đối chiếu nguồn \(/).click();
  await expect(page.getByText(reviewNote, {exact: true})).toBeVisible();
  await expect(page.getByRole("button", {name: "Ghi kết quả đối chiếu"})).toHaveCount(0);
  await expect(page.getByLabel("Ghi chú riêng của bạn")).toHaveValue("");
});

test("KG self-study hides basis until submission and keeps it after reload", async ({page}) => {
  const modelRequests: string[] = [];
  page.on("request", request => {if (/chat\/completions|embeddings/.test(request.url())) modelRequests.push(request.url());});
  await login(page);
  await page.goto("/knowledge?id=FIXTURE%3ACONDITION");
  await page.getByRole("link", {name: "Tự luyện từ nội dung này", exact: true}).click();
  await expect(page).toHaveURL(/\/exams\?node=/);
  await page.getByLabel("Nguồn câu hỏi", {exact: true}).selectOption("kg");
  await expect(page.getByText(/Theo Sách dùng trong kiểm thử/)).toBeVisible();
  await page.getByRole("button", {name: "Chọn 5 câu đầu trang", exact: true}).click();
  await page.getByRole("button", {name: "Bắt đầu bài 1 câu", exact: true}).click();
  await expect(page).toHaveURL(/session=/);
  const id = new URL(page.url()).searchParams.get("session");
  const draft = await (await api(page, `/study/sessions/${id}`)).json();
  expect(draft.questions[0].origin).toBe("kg_template");
  expect(draft.questions[0].study_basis).toBeUndefined();
  expect(draft.questions[0].sources.every((s: {excerpt: string}) => s.excerpt === "")).toBe(true);
  await page.getByLabel("Câu trả lời 1", {exact: true}).fill("Bài làm tổng hợp từ dữ liệu thử, không phải nội dung y khoa.");
  await page.getByRole("button", {name: "Lưu nháp", exact: true}).click();
  await expect(page.getByText("Đã lưu bản nháp vào tài khoản.", {exact: true})).toBeVisible();
  await page.reload();
  await expect(page.getByLabel("Câu trả lời 1", {exact: true})).toHaveValue("Bài làm tổng hợp từ dữ liệu thử, không phải nội dung y khoa.");
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", {name: "Hoàn tất bài", exact: true}).click();
  await page.getByText("Nội dung nguồn để tự đối chiếu — không phải đáp án chấm điểm", {exact: true}).click();
  await expect(page.getByText("Nội dung thử nghiệm, không dùng học y khoa.", {exact: true})).toBeVisible();
  const complete = await (await api(page, `/study/sessions/${id}`)).json();
  expect(complete.questions[0].study_basis).toHaveLength(1);
  expect(complete.graded).toBe(false); expect(complete.score).toBeNull();
  await page.reload();
  const reread = await (await api(page, `/study/sessions/${id}`)).json();
  expect(reread.questions).toEqual(complete.questions);
  expect(modelRequests).toEqual([]);
});
