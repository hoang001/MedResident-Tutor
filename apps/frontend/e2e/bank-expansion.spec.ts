import {test, expect} from "@playwright/test";
import fs from "node:fs";

const root="/workspace/data/authoring/bank-expansion-20261116";
test("100-question bank, source-pinned mock attempts in isolated test DB",async({page})=>{
  const errors:string[]=[];
  page.on("pageerror",e=>errors.push(e.message));
  await page.route("http://localhost:8000/api/v1/**",route=>route.continue({url:route.request().url().replace("http://localhost:8000","http://host.docker.internal:8105")}));
  await page.goto("http://host.docker.internal:3000/login");
  await page.getByLabel("Email",{exact:true}).fill("bank-workflow-test@example.com");
  await page.getByLabel("Mật khẩu",{exact:true}).fill("BankWorkflowOnly123!");
  await page.getByRole("button",{name:"Đăng nhập",exact:true}).click();
  await expect(page).toHaveURL(/learn/);
  await expect(page.getByText("100 câu khả dụng.",{exact:false})).toBeVisible();
  await page.getByRole("button",{name:"Trang sau",exact:true}).click();
  await expect(page.getByRole("status").filter({hasText:"Trang 2/10"})).toBeVisible();
  await page.getByLabel("Tìm nội dung hoặc mã câu").fill("khuYU");
  await page.getByRole("button",{name:"Trật khớp khuỷu",exact:true}).click();
  await expect(page.getByRole("status").filter({hasText:"8 câu khớp"})).toBeVisible();
  await page.screenshot({path:root+"/learn-desktop.png",fullPage:true});
  const samples=["ORTHO_B21CN1_Q_0013","QB26_SHOULDER_STABILIZERS","QB26_SOFT_GRAFT_FLAP","QB26_SPINE_CT_MRI_COMPLEMENT","QB26_NECK_OCCULT_FRACTURE"];
  const proof=[];
  for(const id of samples){
    await page.goto("http://host.docker.internal:3000/learn?question="+id);
    await expect(page.locator("#practice-question")).toHaveValue(id);
    expect(await page.getByTestId("practice-result").count()).toBe(0);
    await expect(page.getByRole("heading",{name:"Đáp án tham khảo của phiên bản đã làm"})).toHaveCount(0);
    await page.getByLabel("Câu trả lời",{exact:true}).fill("Bài nộp kiểm thử giao diện trên DB test; không đánh giá nội dung y khoa.");
    const submitted=page.waitForResponse(r=>r.url().endsWith("/practice/attempts")&&r.request().method()==="POST");
    await page.getByRole("button",{name:"Gửi câu trả lời",exact:true}).click();
    const response=await submitted; expect(response.status()).toBe(200);
    const a=await response.json();
    expect(a.execution_mode).toBe("mock");
    expect(a.retrieval.effective_strategy).toBe("approved_package");
    expect(a.retrieval.neo4j_queries).toBe(0); expect(a.retrieval.vector_search).toBe(false);
    expect(a.reference_answer.length).toBeGreaterThan(20);
    expect(a.medical_evaluation.rubric_scores.length).toBeGreaterThanOrEqual(2);
    await expect(page.getByTestId("practice-result")).toBeVisible();
    await expect(page.getByRole("heading",{name:"Đáp án tham khảo của phiên bản đã làm"})).toBeVisible();
    await expect(page.getByRole("heading",{name:"Evidence được tham chiếu"})).toBeVisible();
    await page.reload();
    await expect(page.getByTestId("practice-result")).toBeVisible();
    await expect(page.getByTestId("attempt-id")).toHaveText(a.id);
    await expect(page.getByRole("button",{name:id+" · completed",exact:true}).first()).toBeVisible();
    proof.push({question_id:id,attempt_id:a.id,mode:a.execution_mode,snapshot_hash:a.snapshot_hash,reference_answer:a.reference_answer,retrieval:a.retrieval,criteria:a.medical_evaluation.rubric_scores.map((c:{criterion_id:string})=>c.criterion_id),source_ids:a.evidence.map((e:{source_id:string})=>e.source_id)});
  }
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:root+"/learn-mobile-result.png",fullPage:true});
  await page.goto("http://host.docker.internal:3000/learn?question=CLINICAL_DEMO_V1_CASE01");
  await expect(page.locator("#practice-question")).toHaveValue("CLINICAL_DEMO_V1_CASE01");
  const images=page.locator("main img"); await expect(images.first()).toBeVisible({timeout:10000});
  for(const img of await images.all()) await expect.poll(()=>img.evaluate((e:HTMLImageElement)=>e.complete&&e.naturalWidth>0)).toBe(true);
  await page.goto("file:///workspace/data/authoring/bank-expansion-20261116/review.html");
  await expect(page.getByRole("heading",{name:"Rà soát ngân hàng câu hỏi",exact:true})).toBeVisible();
  await page.locator("#topic").selectOption("spine");
  await expect(page.locator("#count")).toHaveText("8 câu phù hợp");
  await page.locator(".question:not([hidden]) > summary").first().click();
  await expect(page.getByRole("heading",{name:"Đáp án tham khảo",exact:true}).first()).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:root+"/review-mobile.png",fullPage:false});
  await page.setViewportSize({width:1365,height:900});
  await page.screenshot({path:root+"/review-desktop.png",fullPage:false});
  expect(errors).toEqual([]);
  fs.writeFileSync(root+"/browser-proof.json",JSON.stringify({database:"medresident_test_bank_browser_20261116",real_model_calls:0,grading:"explicit_mock",cases:proof,existing_case_images_loaded:true,main_database_attempt_writes:0,page_errors:errors},null,2));
});
